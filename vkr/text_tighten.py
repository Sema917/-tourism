def _sentences(text):
    """Делит абзац на предложения и не режет инициалы."""
    import re
    raw = re.split(r"(?<=[.!?])\s+", text.strip())
    out = []
    buf = ""
    for part in raw:
        buf = (buf + " " + part).strip()
        if len(buf) < 28 or re.search(r"[А-Я]\.$", buf):
            continue
        out.append(buf)
        buf = ""
    if buf:
        if out:
            out[-1] = out[-1] + " " + buf
        else:
            out.append(buf)
    return out


def _trim_paragraph(text):
    import re
    if re.search(r"»\[\d+\]", text):
        return text
    if re.search(r"[Рр]исун|[Тт]аблиц", text):
        return text
    if text.startswith(KEEP_STARTS):
        return text
    if len(re.findall(r"\d{3,}", text)) >= 2:
        return text
    # Цифры, без которых сводка глав перестанет сходиться.
    if re.search(r"процент|Гаврилин|судимост", text):
        return text
    parts = _sentences(text)
    if len(text) < 520 or len(parts) < 4:
        return text
    keep_n = 2 if len(text) > 700 else 3
    kept = list(parts[:keep_n])
    for part in parts[keep_n:]:
        if "«" in part and part not in kept:
            kept.append(part)
    return " ".join(kept)


def _short_lead(text):
    """У длинного подвода к цитате с номером источника оставляет первое предложение."""
    import re
    match = re.search(r"«[^»]*»\[\d+\]", text)
    if not match:
        return text
    lead = text[: match.start()]
    if len(lead) < 250:
        return text
    parts = _sentences(lead)
    if len(parts) < 2:
        return text
    return parts[0] + " " + text[match.start():]


def tighten(blocks):
    out = []
    for block in blocks:
        if block[0] == "p":
            text = block[1]
            for key, new in SHORT.items():
                if text.startswith(key):
                    text = new
                    break
            text = _trim_paragraph(text)
            text = _short_lead(text)
            out.append(("p", text))
        else:
            out.append(block)
    return out
