def _block(doc, block):
    h2(doc, f"{block['time']}   {block['title']}")
    rich(doc, [("Слайды. ", {"bold": True, "color": TEAL}), (block["slides"], {"color": INK})], after=2)
    rich(doc, [("Задача. ", {"bold": True, "color": NAVY}), (block["goal"], {})], after=4)
    p(doc, "Опорный текст", size=11, color=TEAL, bold=True, after=2)
    for para in block["say"]:
        p(doc, para, size=11, after=4)
    if block.get("do"):
        p(doc, "Что происходит в зале", size=11, color=NAVY, bold=True, after=2)
        for item in block["do"]:
            bullet(doc, item)
    if block.get("age"):
        p(doc, "Возраст", size=11, color=NAVY, bold=True, before=4, after=2)
        p(doc, block["age"], size=11)
    if block.get("cut"):
        p(doc, "Если не успеваете", size=11, color="A86B12", bold=True, before=2, after=2)
        p(doc, block["cut"], size=11)
    if block.get("trouble"):
        p(doc, "Если идёт не так", size=11, color=NAVY, bold=True, before=2, after=2)
        p(doc, block["trouble"], size=11)


