W = 18.0


def build_all():
    return (
        _build(60, "/workspace/materials/Путь_в_профессию_сценарий_60_минут.docx", "Полный сюжет встречи на один час", BLOCKS_60, 21, False),
        _build(20, "/workspace/materials/Путь_в_профессию_сценарий_20_минут.docx", "Экспресс-сюжет той же встречи", BLOCKS_20, 11, True),
    )


def _build(minutes, filename, subtitle, blocks, slides, express):
    doc = new_doc(f"Наука 0+   ·   Путь в профессию   ·   сценарий {minutes} минут   ·   комплект {VERSION}")
    doc.core_properties.title = f"Путь в профессию. Сценарий на {minutes} минут"
    doc.core_properties.subject = subtitle
    _passport(doc, minutes, subtitle, slides, express)
    _goals(doc, minutes)
    _prepare(doc, minutes)
    h1(doc, "Ход встречи")
    p(doc, "Большая часть встречи — рассказ ведущего по ярким слайдам. Интерактивов немного, и в сценарии они помечены словом «ИНТЕРАКТИВ». Остальные блоки не превращайте в опросы зала.")
    for block in blocks:
        _block(doc, block)
    page_break(doc)
    _appendix(doc, express)
    doc.save(filename)
    return filename


def _passport(doc, minutes, subtitle, slides, express):
    p(doc, "ФЕСТИВАЛЬ  «НАУКА 0+»", size=12, color=TEAL, bold=True, after=2)
    p(doc, "Путь в профессию", size=28, color=NAVY, bold=True, after=2, line=1.0)
    p(doc, subtitle, size=14, after=4)
    p(doc, f"Сценарий ведущего  ·  {minutes} минут  ·  5–11 класс  ·  комплект {VERSION}", size=11, color=MUTED, after=8)
    rows = [
        ("Формат", "Презентационный рассказ с картинками + несколько отмеченных интерактивов. Не мастерская «каждое задание — новый опрос»."),
        ("Интерактивы", "Формула «Хочу — Могу — Умею — Надо»; тест ДДО Климова; кейс; письмо себе. Остальное — речь ведущего."),
        ("Метод", "Учебный сокращённый ДДО. " + ("В зале вопросы 1–10." if express else "В зале вопросы 1–15, около 6 минут.")),
        ("Направления", "39.03.01 Социология; 39.03.02 Социальная работа; 41.03.04 Политология; 39.03.03 Организация работы с молодёжью."),
        ("Слайды", f"{slides} слайдов. Заметки докладчика дублируют опоры."),
        ("Тетрадь", "Одна на обе длительности. Не собирают."),
    ]
    table = doc.add_table(rows=len(rows), cols=2)
    set_table_widths(table, [3.4, W - 3.4])
    set_table_borders(table, "E4DCD0", "4")
    for i, (k, v) in enumerate(rows):
        left, right = table.rows[i].cells
        shade_cell(left, "16324A")
        shade_cell(right, "F7F4EE" if i % 2 == 0 else "FFFFFF")
        set_cell_margins(left, 50, 50, 70, 70)
        set_cell_margins(right, 50, 50, 80, 80)
        _cell(left, k, 10, "FFFFFF", True)
        _cell(right, v, 10.5, INK, False)
    p(doc, "", after=4)


def _cell(cell, text, size, color, bold):
    paragraph = cell.paragraphs[0]
    spacing(paragraph, 0, 0, 1.02)
    add_text(paragraph, text, size, color, bold)


def _goals(doc, minutes):
    h1(doc, "Зачем встреча")
    bullet(doc, "Показать выбор профессии как исследование, а не угадывание должности.")
    bullet(doc, "Дать формулу «хочу — могу — умею — надо» и один измеримый шаг.")
    bullet(doc, "Провести короткий ДДО Климова как гипотезу интереса.")
    bullet(doc, "Познакомить с четырьмя направлениями «люди и общество» без рекламы факультета.")
    bullet(doc, "Назвать государственные двери поддержки молодёжи.")
    if minutes == 20:
        p(doc, "За 20 минут не пытайтесь проговорить часовой текст быстрее. Глубина остаётся в тетради.", before=4)


def _prepare(doc, minutes):
    h1(doc, "До встречи")
    bullet(doc, "Презентация, сценарий и тетрадь одной версии комплекта.")
    bullet(doc, "Тетрадь на каждого. Ручки. Таймер. Проектор с цветом — слайды рассчитаны на картинки.")
    bullet(doc, "Не фотографируйте листы с ответами крупным планом.")
    bullet(doc, "Запрет для себя: не оценивать детей, не сравнивать баллы, не обещать зарплату, не делить профессии по полу.")
    callout(
        doc,
        "Как вести",
        "Слайды без пометы «ИНТЕРАКТИВ» — ваш рассказ. Не превращайте их в голосования и работу в парах. Хватит 3–4 настоящих интерактивов за час.",
    )


def _block(doc, block):
    h2(doc, f"{block['time']}   {block['title']}")
    rich(doc, [("Слайды. ", {"bold": True, "color": TEAL}), (block["slides"], {"color": INK})], after=2)
    rich(doc, [("Задача. ", {"bold": True, "color": NAVY}), (block["goal"], {})], after=3)
    if block.get("interactive"):
        callout(doc, "ИНТЕРАКТИВ", block["interactive"], "FDE8E2", "E15A3A")
    p(doc, "Опорный текст", size=11, color=TEAL, bold=True, after=2)
    for para in block["say"]:
        p(doc, para, size=11, after=4)
    if block.get("do"):
        p(doc, "В зале", size=11, color=NAVY, bold=True, after=2)
        for item in block["do"]:
            bullet(doc, item)
    if block.get("cut"):
        p(doc, "Если не успеваете", size=11, color="A86B12", bold=True, before=2, after=2)
        p(doc, block["cut"], size=11)


def _appendix(doc, express):
    h1(doc, "Приложение")
    h2(doc, "Ключ")
    _print_key(doc, "Полная версия, 1–15", False)
    _print_key(doc, "Экспресс, 1–10", True)
    p(doc, f"Сумма баллов равна числу ответов ({expected_sum(False)} / {expected_sum(True)}). Максимум столбца — {max_score(False)} / {max_score(True)}.")
    h2(doc, "Сокращение ДДО")
    p(doc, "Из классических 20 пар не вошли " + ", ".join(DROPPED_CLASSIC) + ". В 15 парах каждый тип встречается 6 раз; в экспрессе 1–10 — по 4 раза.")
    for q in QUESTIONS:
        note = " Адаптация пункта про клавишные машины." if q["note"] else ""
        bullet(doc, f"Комплект {q['n']} — классический {q['classic']}. А — {q['a_type']}, Б — {q['b_type']}.{note}")
    h2(doc, "Запасные ходы к кейсу")
    for role, text in CASE_SAMPLES:
        p(doc, role, size=11, color=NAVY, bold=True, before=4, after=1)
        p(doc, text, size=11)
    h2(doc, "Не говорите")
    for line in (
        "«Тебе это не подходит».",
        "«С твоими оценками одна дорога».",
        "«Нормальная профессия — это…».",
        "Сравнение баллов двух участников.",
        "Обещание зарплаты или целевого места.",
        "«Политолог = политик», «социальный педагог = специалист по социальной работе».",
    ):
        bullet(doc, line)
    h2(doc, "Источники")
    for item in SOURCES:
        bullet(doc, item)


def _print_key(doc, title, express):
    p(doc, title, size=12, color=NAVY, bold=True, before=6, after=2)
    for code in TYPE_ORDER:
        bullet(doc, f"{code} · {TYPE_SHORT[code]}: {', '.join(answers_by_type(express)[code])}")


