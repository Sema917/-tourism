def _prepare(doc, minutes):
    h1(doc, "До встречи")
    bullet(doc, "Проверьте, что презентация, сценарий и тетрадь одного комплекта 2026.1. Ключ на слайде и ключ в тетради должны совпасть.")
    bullet(doc, "Распечатайте тетрадь на каждого: А4, можно чёрно-белую, двустороннюю, скоба. Разложите закрытой на обложке.")
    bullet(doc, "Ручки. Таймер. Вода. Если есть фотограф, договоритесь: листы с ответами в кадр не берут.")
    bullet(doc, "План зала А: группы по 4 человека, если будет полный кейс. План Б: ряды, которые не сдвинуть. Тогда кейс делают вдвоём или каждый сам, роли не теряются.")
    bullet(doc, "Узнайте, кто сопровождает класс. Если ребёнок сообщит о беде дома, в зале это не разбирают. После встречи говорят сопровождающему педагогу.")
    bullet(doc, "Проговорите про себя запрет: не оценивать детей, не сравнивать баллы, не обещать зарплату, не делить профессии на «для девочек» и «для мальчиков».")
    if minutes == 60:
        p(doc, "Лучше всего 15–30 человек. Больше тридцати — кейс парами, вслух две команды. Меньше восьми — четыре добровольца берут роли при всех, остальные дополняют.", before=2)
