def _build(minutes, filename, subtitle, blocks, slides, express):
    doc = new_doc(f"Наука 0+   ·   Путь в профессию   ·   сценарий {minutes} минут   ·   комплект {VERSION}")
    doc.core_properties.title = f"Путь в профессию. Сценарий на {minutes} минут"
    doc.core_properties.subject = subtitle
    _passport(doc, minutes, subtitle, slides, express)
    _goals(doc)
    _prepare(doc)
    h1(doc, "Ход встречи")
    p(doc, "Порядок жёсткий: кейс → информация → интерактив → информация → интерактив → информация → тест и типы профессий → сборка кейса → письмо. Слайды без пометы «ИНТЕРАКТИВ» — ваш рассказ простым языком.")
    for block in blocks:
        _block(doc, block)
    page_break(doc)
    _appendix(doc, express)
    doc.save(filename)
    return filename


def _passport(doc, minutes, subtitle, slides, express):
    p(doc, "ФЕСТИВАЛЬ  «НАУКА 0+»", size=12, color=TEAL, bold=True, after=2)
    p(doc, "Путь в профессию", size=28, color=NAVY, bold=True, after=2, line=1.0)
    p(doc, subtitle, size=14, after=4)
    p(doc, f"Сценарий ведущего  ·  {minutes} минут  ·  5–11 класс  ·  комплект {VERSION}", size=11, color=MUTED, after=8)
    rows = [
        ("Логика", "Сначала кейс. Потом два интерактива, которые помогают его решить. Между ними — короткие объяснения. Затем тест Климова и формула типов профессий. В конце — письмо себе."),
        ("Интерактивы", "1) Разведка для кейса. 2) «Хочу — могу — умею — надо». 3) Тест ДДО. 4) Сборка кейса. 5) Письмо. Не превращайте информационные слайды в опросы."),
        ("Язык", "Говорите просто. На слайдах нет дат приёмной кампании, лимитов заявлений и полного списка льгот — это в тетради для дома."),
        ("Метод", "Сокращённый ДДО. " + ("В зале вопросы 1–10." if express else "В зале вопросы 1–15.")),
        ("Слайды", f"{slides} слайдов."),
        ("Тетрадь", "Одна на обе длительности. Не собирают."),
    ]
    table = doc.add_table(rows=len(rows), cols=2)
    set_table_widths(table, [3.2, W - 3.2])
    set_table_borders(table, "E4DCD0", "4")
    for i, (k, v) in enumerate(rows):
        left, right = table.rows[i].cells
        shade_cell(left, "16324A")
        shade_cell(right, "F7F4EE" if i % 2 == 0 else "FFFFFF")
        set_cell_margins(left, 50, 50, 70, 70)
        set_cell_margins(right, 50, 50, 80, 80)
        _cell(left, k, 10, "FFFFFF", True)
        _cell(right, v, 10.5, INK, False)


def _cell(cell, text, size, color, bold):
    paragraph = cell.paragraphs[0]
    spacing(paragraph, 0, 0, 1.02)
    add_text(paragraph, text, size, color, bold)


def _goals(doc):
    h1(doc, "Зачем")
    bullet(doc, "Дать школьникам задачу (кейс) и инструменты для её решения.")
    bullet(doc, "Объяснить выбор профессии простыми словами, без лишней бюрократии на экране.")
    bullet(doc, "Провести формулу «хочу — могу — умею — надо» и сокращённый ДДО.")
    bullet(doc, "Показать четыре направления «люди и общество» как пример, не как единственный путь.")


def _prepare(doc):
    h1(doc, "До встречи")
    bullet(doc, "Презентация, сценарий и тетрадь одной версии 2026.2.")
    bullet(doc, "Тетрадь каждому. Ручки. Таймер. Цветной проектор.")
    bullet(doc, "Не оценивайте ответы и не сравнивайте баллы.")
    callout(doc, "Важно", "Информационные блоки — это объяснение. Не просите зал «обсудить в парах» каждый слайд. Иначе снова получится бесконечный воркшоп.")


def _block(doc, block):
    h2(doc, f"{block['time']}   {block['title']}")
    rich(doc, [("Слайды. ", {"bold": True, "color": TEAL}), (block["slides"], {"color": INK})], after=2)
    rich(doc, [("Задача. ", {"bold": True, "color": NAVY}), (block["goal"], {})], after=3)
    if block.get("interactive"):
        callout(doc, "ИНТЕРАКТИВ", block["interactive"], "FDE8E2", "E15A3A")
    if block.get("info"):
        callout(doc, "ИНФОРМАЦИЯ", block["info"], "E7F3F1", "0F7A6C")
    p(doc, "Опорный текст", size=11, color=TEAL, bold=True, after=2)
    for para in block["say"]:
        p(doc, para, size=11, after=4)
    if block.get("do"):
        p(doc, "В зале", size=11, color=NAVY, bold=True, after=2)
        for item in block["do"]:
            bullet(doc, item)
    if block.get("cut"):
        p(doc, "Если не успеваете", size=11, color="A86B12", bold=True, before=2, after=2)
        p(doc, block["cut"], size=11)


def _appendix(doc, express):
    h1(doc, "Приложение")
    h2(doc, "Ключ")
    for title, flag in (("Полная версия 1–15", False), ("Экспресс 1–10", True)):
        p(doc, title, size=12, color=NAVY, bold=True, before=6, after=2)
        for code in TYPE_ORDER:
            bullet(doc, f"{code} · {TYPE_SHORT[code]}: {', '.join(answers_by_type(flag)[code])}")
    p(doc, f"Сумма = {expected_sum(False)} / {expected_sum(True)}. Максимум столбца = {max_score(False)} / {max_score(True)}.")
    h2(doc, "Сокращение ДДО")
    p(doc, "Не вошли классические пары " + ", ".join(DROPPED_CLASSIC) + ".")
    for q in QUESTIONS:
        note = " Адаптация пункта про клавишные машины." if q["note"] else ""
        bullet(doc, f"Комплект {q['n']} — классический {q['classic']}. А — {q['a_type']}, Б — {q['b_type']}.{note}")
    h2(doc, "Запасные ходы к кейсу")
    for role, text in CASE_SAMPLES:
        p(doc, role, size=11, color=NAVY, bold=True, before=4, after=1)
        p(doc, text, size=11)
    h2(doc, "Источники")
    for item in SOURCES:
        bullet(doc, item)


