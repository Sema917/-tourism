def _build(minutes, filename, subtitle, blocks, slides, express):
    doc = new_doc(f"Наука 0+   ·   Путь в профессию   ·   сценарий {minutes} минут   ·   комплект {VERSION}")
    doc.core_properties.title = f"Путь в профессию. Сценарий на {minutes} минут"
    doc.core_properties.subject = subtitle
    _passport(doc, minutes, subtitle, slides, express)
    _goals(doc, minutes)
    _prepare(doc, minutes)
    _never(doc, minutes)
    h1(doc, "Ход встречи")
    p(doc, "Опорный текст можно говорить близко к записи. В скобках — действия, их вслух не читают. Если отстаёте от часов, режьте по пометке «если не успеваете», а не наугад.", size=11)
    for block in blocks:
        _block(doc, block)
    page_break(doc)
    _appendix(doc, express)
    doc.save(filename)
    return filename


