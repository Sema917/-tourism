def build_all():
    path = _build(
        "/workspace/materials/Путь_в_профессию_сценарий_20_минут.docx",
        "Экспресс 20 минут · дословный текст ведущего",
        BLOCKS,
        26,
    )
    alias = "/workspace/materials/Путь_в_профессию_сценарий_60_минут.docx"
    _build(alias, "Экспресс 20 минут · дословный текст ведущего", BLOCKS, 26)
    return path, alias


def _build(filename, subtitle, blocks, slides):
    doc = new_doc(f"Наука 0+   ·   Путь в профессию   ·   сценарий 20 минут   ·   {VERSION}")
    doc.core_properties.title = "Путь в профессию. Сценарий на 20 минут"
    doc.core_properties.subject = subtitle
    _passport(doc, subtitle, slides)
    h1(doc, "Как читать этот сценарий")
    p(
        doc,
        "Ниже — текст, который можно говорить почти слово в слово. "
        "В скобках — короткие подсказки для себя: что сделать руками, куда смотреть, сколько ждать. "
        "Их вслух не читайте.",
        size=11,
        after=4,
    )
    p(
        doc,
        "Говорите спокойно, как обычно разговариваете с людьми. Не нужно «красивых» фраз. "
        "Если видите, что класс молчит и пишет — подождите. Если кто-то шумит на опросе — просто напомните правило.",
        size=11,
        after=8,
    )
    h1(doc, "Текст ведущего")
    for block in blocks:
        _block(doc, block)
    page_break(doc)
    _appendix(doc)
    doc.save(filename)
    return filename


def _passport(doc, subtitle, slides):
    p(doc, "ФЕСТИВАЛЬ  «НАУКА 0+»", size=12, color=TEAL, bold=True, after=2)
    p(doc, "Путь в профессию", size=26, color=INK_DEEP, bold=True, after=2, line=1.0)
    p(doc, subtitle, size=13, after=4)
    p(doc, f"Сценарий  ·  20 минут  ·  5–11 класс  ·  комплект {VERSION}", size=11, color=MUTED, after=8)
    rows = [
        ("Формат", "20 минут. Раздатка — одна страница: четыре клетки и 15 пар опроса."),
        ("Текст", "Дословные реплики ведущего. Без лозунгов и сложных слов."),
        ("Опрос", "Вопросы на слайдах. Ответ отмечают в раздатке."),
        ("Слайды", f"{slides} слайдов."),
    ]
    table = doc.add_table(rows=len(rows), cols=2)
    set_table_widths(table, [3.2, W - 3.2])
    set_table_borders(table, "D2DBE3", "4")
    for i, (k, v) in enumerate(rows):
        left, right = table.rows[i].cells
        shade_cell(left, INK_DEEP)
        shade_cell(right, "F7FAFB" if i % 2 == 0 else "FFFFFF")
        set_cell_margins(left, 50, 50, 70, 70)
        set_cell_margins(right, 50, 50, 80, 80)
        _cell(left, k, 10, "FFFFFF", True)
        _cell(right, v, 10.5, INK, False)


def _cell(cell, text, size, color, bold):
    paragraph = cell.paragraphs[0]
    spacing(paragraph, 0, 0, 1.02)
    add_text(paragraph, text, size, color, bold)


def _block(doc, block):
    h2(doc, f"{block['time']}   {block['title']}")
    rich(doc, [("Слайды. ", {"bold": True, "color": TEAL}), (block["slide"], {"color": INK})], after=3)
    if block.get("do"):
        callout(doc, "ДЕЛАЕТЕ", block["do"], "E6F5F2", "0B8A7A")
    for para in block["say"]:
        if para.startswith("(") and para.endswith(")"):
            p(doc, para, size=10.5, italic=True, color=MUTED, after=3)
        else:
            p(doc, para, size=11.5, after=4)
    if block.get("cut"):
        p(doc, "Если времени мало: " + block["cut"], size=11, color="C47A1A", after=4)


def _appendix(doc):
    h1(doc, "Приложение для ведущего")
    h2(doc, "Ключ опроса · 15 пар")
    p(doc, "Это для вас, не для экрана, пока не скажете «считаем».", size=11, after=3)
    for code in TYPE_ORDER:
        bullet(doc, f"{code} · {TYPE_SHORT[code]}: {', '.join(answers_by_type(False)[code])}")
    p(doc, f"Сумма баллов по всем ответам — {expected_sum(False)}. В одном столбце максимум {max_score(False)}.", size=11, after=4)
    h2(doc, "Как устроен сокращённый опрос")
    p(doc, "Не вошли классические пары " + ", ".join(DROPPED_CLASSIC) + ".", size=11, after=2)
    for q in QUESTIONS:
        note = " Учебная правка формулировки." if q["note"] else ""
        bullet(doc, f"{q['n']} ← классический {q['classic']}. А={q['a_type']}, Б={q['b_type']}.{note}")
    h2(doc, "Источники")
    for item in SOURCES:
        bullet(doc, item)


