def append_text_preserve_style(paragraph, text: str) -> None:
    """Добавляет текст в конец абзаца, копируя стиль последнего run."""
    if paragraph.runs:
        last = paragraph.runs[-1]
        new_run = paragraph.add_run(text)
        new_run.bold = last.bold
        new_run.italic = last.italic
        new_run.underline = last.underline
        if last.font is not None:
            if last.font.name:
                new_run.font.name = last.font.name
            if last.font.size:
                new_run.font.size = last.font.size
            if last.font.color and last.font.color.rgb:
                new_run.font.color.rgb = last.font.color.rgb
        # Preserve East Asian / complex script font if present
        rPr = last._element.get_or_add_rPr()
        rFonts = rPr.find(qn("w:rFonts"))
        if rFonts is not None:
            new_rPr = new_run._element.get_or_add_rPr()
            new_rFonts = new_rPr.find(qn("w:rFonts"))
            if new_rFonts is None:
                new_rFonts = deepcopy(rFonts)
                new_rPr.insert(0, new_rFonts)
            else:
                for attr in list(rFonts.attrib):
                    new_rFonts.set(attr, rFonts.get(attr))
    else:
        paragraph.add_run(text)


def main() -> None:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(SRC, OUT)
    doc = Document(str(OUT))

    # 1) Вставить цитаты
    for idx, frags in CITATIONS.items():
        p = doc.paragraphs[idx]
        original = p.text
        addition = "".join(frags)
        # Защита: исходный текст должен остаться префиксом
        append_text_preserve_style(p, addition)
        assert p.text.startswith(original), f"Paragraph {idx} original text changed"

    # 2) Дополнить список литературы
    # Найти последний абзац библиографии (после заголовка СПИСОК ЛИТЕРАТУРЫ)
    lit_idx = next(
        i for i, p in enumerate(doc.paragraphs) if "СПИСОК ЛИТЕРАТУРЫ" in p.text
    )
    # Стиль берём у существующей записи (п. 9)
    style_ref = None
    for i in range(lit_idx + 1, len(doc.paragraphs)):
        if doc.paragraphs[i].text.strip().startswith("9."):
            style_ref = doc.paragraphs[i]
            break
    if style_ref is None:
        style_ref = doc.paragraphs[lit_idx + 1]

    # Вставляем новые источники после последнего непустого абзаца литературы
    insert_after = lit_idx
    for i in range(lit_idx + 1, len(doc.paragraphs)):
        if doc.paragraphs[i].text.strip():
            insert_after = i
        else:
            # пустой абзац после литературы — останавливаемся на последней записи
            break

    # python-docx: insert paragraphs after element
    ref_element = doc.paragraphs[insert_after]._element
    for src in NEW_SOURCES:
        new_p = deepcopy(style_ref._element)
        # clear text in new_p and set
        # Simpler: use add_paragraph then move — but order matters.
        # Create via XML clone of style paragraph
        for child in list(new_p):
            # remove all runs / hyperlinks content but keep pPr
            if child.tag != qn("w:pPr"):
                new_p.remove(child)
        # add a run with text
        from docx.oxml import OxmlElement

        r = OxmlElement("w:r")
        # copy rPr from style_ref first run if any
        if style_ref.runs:
            rPr_src = style_ref.runs[0]._element.find(qn("w:rPr"))
            if rPr_src is not None:
                r.append(deepcopy(rPr_src))
        t = OxmlElement("w:t")
        t.set(qn("xml:space"), "preserve")
        t.text = src
        r.append(t)
        new_p.append(r)
        ref_element.addnext(new_p)
        ref_element = new_p

    doc.save(str(OUT))

    # 3) Проверка доли цитирования
    doc2 = Document(str(OUT))
    paras = [p.text for p in doc2.paragraphs]
    start = next(i for i, t in enumerate(paras) if t.strip() == "ВВЕДЕНИЕ")
    end = next(i for i, t in enumerate(paras) if "СПИСОК ЛИТЕРАТУРЫ" in t)
    body = "\n".join(
        t
        for t in paras[start + 1 : end]
        if t.strip()
        and not t.strip().startswith("Рисунок ")
        and not t.strip().startswith("Таблица ")
        and t.strip()
        not in {
            "ПОДХОДЫ К ОТБОРУ И ОСНОВАНИЕ КРИТЕРИЯ",
            "ПОСТАНОВКА ЗАДАЧИ",
            "МЕСТО РАСЧЁТА В ГОДОВОМ ЦИКЛЕ",
            "ПРОЦЕДУРА ОТБОРА",
            "СВОЙСТВА ПРОЦЕДУРЫ И ГРАНИЦЫ ПРИМЕНИМОСТИ",
            "ЧИСЛЕННЫЙ ЭКСПЕРИМЕНТ",
            "ЗАКЛЮЧЕНИЕ",
        }
    )

    # Цитаты в формате "..."[n]
    cited_parts = re.findall(r'"[^"]+"\[\d+\]', body)
    cited_text = "".join(cited_parts)
    # Также посчитаем содержимое кавычек
    quoted_only = "".join(re.findall(r'"([^"]+)"\[\d+\]', body))

    body_chars = len(body.replace(" ", "").replace("\n", ""))
    cited_chars = len(cited_text.replace(" ", "").replace("\n", ""))
    quoted_chars = len(quoted_only.replace(" ", "").replace("\n", ""))

