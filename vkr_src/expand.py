"""Вставки цитат из учебника по древесиноведению и ссылки на остальные источники."""

import pathlib

QUOTES = pathlib.Path(__file__).with_name("quotes_wood.txt")


def wood_quotes():
    if not QUOTES.exists():
        return []
    out = [(
        "p",
        "Координата, которую контроллер выдает на диск, определяется припуском на усушку и зоной бревна, направляемой в доску. Ниже свойства древесины приведены формулировками учебника по древесиноведению. Для технолога они задают ограничения карты реза. Контроллер эти величины не вычисляет и отрабатывает готовый размер."
    )]
    for block in QUOTES.read_text().split("\n\n"):
        block = block.strip()
        if not block or block.startswith("### Свойства"):
            break
        if block.startswith("### "):
            out.append(("p", block[4:].strip()))
            continue
        if "«" in block or "»" in block:
            continue
        out.append(("p", f"«{block}»[1]"))
    out.append((
        "p",
        "Для линии из этого перечня следует разделение функций. Технолог назначает припуск на усушку и определяет, направлять ли сердцевину в низкий сорт. Карта реза содержит готовый размер. Контроллер сушку доски не выполняет и сучок не оценивает: он выводит портал и диски в положение, заданное картой, и снимает ход по концевому выключателю. Сбежистость, кривизна и крупные сучки определяют поштучную распиловку бревна на этой линии вместо одного группового постава на пачку [7; 33; 34; 35; 37; 38; 39; 41; 43]."
    ))
    return out


def expand_chapter1(blocks):
    extra = wood_quotes()
    if not blocks:
        return blocks
    return blocks[:-1] + extra + blocks[-1:]


