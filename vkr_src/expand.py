"""Вставки цитат из учебника по древесиноведению и ссылки на остальные источники."""

import pathlib

QUOTES = pathlib.Path(__file__).with_name("quotes_wood.txt")


def wood_quotes():
    if not QUOTES.exists():
        return []
    out = [(
        "p",
        "Размер, который контроллер выводит на диск, бессмыслен без припуска на усушку и без понимания, какая зона бревна пойдет в доску. Ниже свойства древесины даны формулировками учебника по древесиноведению. Технолог читает их как ограничения карты реза. Контроллер их не вычисляет: он отрабатывает уже готовый размер."
    )]
    for block in QUOTES.read_text().split("\n\n"):
        block = block.strip()
        if not block or block.startswith("### Свойства"):
            break
        if block.startswith("### "):
            out.append(("p", block[4:].strip()))
            continue
        if "«" in block or "»" in block:
            continue
        out.append(("p", f"«{block}»[1]"))
    out.append((
        "p",
        "Из этого набора для линии следует простое разделение труда. Технолог закладывает припуск на усушку и решает, уводить ли сердцевину в низкий сорт. Карта реза уже содержит готовый размер. Контроллер не сушит доску и не оценивает сучок: он выводит портал и диски в положение, которое задано картой, и снимает ход по концевому выключателю. Сбежистость, кривизна и крупные сучки как раз объясняют, почему на этой линии бревно пилят поштучно, а не одним групповым поставом на всю пачку [7; 33; 34; 35; 37; 38; 39; 41; 43]."
    ))
    return out


def expand_chapter1(blocks):
    extra = wood_quotes()
    if not blocks:
        return blocks
    return blocks[:-1] + extra + blocks[-1:]


